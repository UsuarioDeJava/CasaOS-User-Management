LANGUAGES = {"en": "en", "pt": "pt_br"}


def pick_language(accept_languages):
    best = accept_languages.best_match(["en", "pt"], default="en")
    return LANGUAGES[best]


def translate(lang, key, **params):
    text = TEXTS[lang].get(key) or TEXTS["en"].get(key) or key
    return text.format(**params) if params else text
